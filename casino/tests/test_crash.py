class TestCommitmentOrdering:
    def test_stake_salt_refused_for_new_chain_at_init(self):
        with pytest.raises(CommitmentOrderError):
            HashChain("fresh-secret", length=6, salt=STAKE_SALT)

    def test_stake_salt_refused_at_bind(self):
        hc = HashChain("fresh-secret", length=6)
        with pytest.raises(CommitmentOrderError):
            hc.bind_salt(STAKE_SALT)

    def test_stake_salt_refused_in_chain_simulator(self):
        with pytest.raises(CommitmentOrderError):
            simulate_chain_targets([2.0], 100, secret_seed="s",
                                   salt=STAKE_SALT, progress=False)

    def test_cannot_play_before_salt_bound(self):
        hc = HashChain("fresh-secret", length=6)
        assert hc.salt is None
        with pytest.raises(RuntimeError, match="no salt bound"):
            hc.pop_hash()
        with pytest.raises(RuntimeError, match="no salt bound"):
            hc.crash_points(1)
        # the commitment IS available before the salt exists
        assert len(hc.terminating_hash) == 64
        assert hc.commitment["fair_ordering"] is False  # unbound yet

    def test_salt_binds_exactly_once(self):
        hc = HashChain("fresh-secret", length=6)
        hc.bind_salt(TEST_SALT)
        with pytest.raises(CommitmentOrderError, match="already bound"):
            hc.bind_salt(hashlib.sha256(b"other").hexdigest())

    def test_salt_predating_commitment_raises(self):
        hc = HashChain("fresh-secret", length=6)
        stale = hashlib.sha256(b"old block").hexdigest()
        with pytest.raises(CommitmentOrderError, match="predates"):
            hc.bind_salt(stale, revealed_at=hc.committed_at - 3600.0)

    def test_beacon_claim_then_verification_certifies_fair(self):
        # The full honest protocol: commit -> bind a structured beacon
        # CLAIM (mandatory revealed_at, structurally plausible salt) ->
        # the VERIFIER resolves the named index out-of-band and calls
        # verify_salt_against_beacon.  Only then fair_ordering=True.
        for source, salt in (
            (BEACON_SOURCE, FAKE_BLOCK_SALT),
            ({"beacon": "drand", "round": 3_366_570}, DRAND_SALT),
        ):
            hc = HashChain("fresh-secret", length=6)
            time.sleep(0.002)
            revealed = time.time()
            hc.bind_salt(salt, salt_source=source, revealed_at=revealed)
            # a claim alone is NOT a certification
            c = hc.commitment
            assert hc.fair_ordering is False
            assert hc.fair_ordering_claimed is True
            assert c["order"] == "external_commitment_claimed_unverified"
            assert c["fair_ordering"] is False
            assert "verify_salt_against_beacon" in c["note"]
            # verifier's out-of-band resolution: value matches, published
            # strictly after the commitment
            rec = hc.verify_salt_against_beacon(salt, resolved_time=revealed)
            assert hc.fair_ordering is True
            assert rec["order"] == "terminating_hash_first"
            assert rec["fair_ordering"] is True
            assert rec["beacon_verification"]["verified"] is True
            assert rec["salt_bound_at_unix"] >= rec[
                "terminating_hash_committed_at_unix"
            ]
            assert rec["salt_source"] == source
            assert "note" not in rec

    def test_beacon_claim_requires_revealed_at(self):
        hc = HashChain("fresh-secret", length=6)
        with pytest.raises(CommitmentOrderError, match="revealed_at"):
            hc.bind_salt(FAKE_BLOCK_SALT, salt_source=BEACON_SOURCE)

    def test_beacon_claim_future_dated_revealed_at_refused(self):
        hc = HashChain("fresh-secret", length=6)
        with pytest.raises(CommitmentOrderError, match="future"):
            hc.bind_salt(FAKE_BLOCK_SALT, salt_source=BEACON_SOURCE,
                         revealed_at=time.time() + 3600.0)

    def test_beacon_claim_past_reveal_refused_at_bind(self):
        # honestly attesting an ALREADY-PUBLISHED beacon value is refused
        # on the spot — the named index must be a future one
        hc = HashChain("fresh-secret", length=6)
        with pytest.raises(CommitmentOrderError, match="predates"):
            hc.bind_salt(BITCOIN_BLOCK_1_HASH,
                         salt_source={"beacon": "bitcoin", "height": 1},
                         revealed_at=BITCOIN_BLOCK_1_TIME)

    def test_bitcoin_claim_structurally_impossible_salt_refused(self):
        # a claimed Bitcoin block hash with < 8 leading zero nibbles is
        # impossible at ANY height (difficulty-1 proof-of-work floor)
        hc = HashChain("fresh-secret", length=6)
        time.sleep(0.002)
        with pytest.raises(CommitmentOrderError, match="leading zero"):
            hc.bind_salt(TEST_SALT, salt_source=BEACON_SOURCE,
                         revealed_at=time.time())
        for bad in ("not-hex-at-all", "abc123", FAKE_BLOCK_SALT[:-2]):
            hc2 = HashChain("fresh-secret", length=6)
            time.sleep(0.002)
            with pytest.raises(CommitmentOrderError, match="hex"):
                hc2.bind_salt(bad, salt_source=BEACON_SOURCE,
                              revealed_at=time.time())

    def test_verify_requires_a_bound_beacon_claim(self):
        hc = HashChain("fresh-secret", length=6)
        with pytest.raises(RuntimeError, match="no salt bound"):
            hc.verify_salt_against_beacon(TEST_SALT, time.time())
        hc.bind_salt(TEST_SALT, salt_source="free text")
        with pytest.raises(CommitmentOrderError, match="nothing"):
            hc.verify_salt_against_beacon(TEST_SALT, time.time())

    def test_verify_mismatched_value_refutes_claim(self):
        hc = HashChain("fresh-secret", length=6)
        time.sleep(0.002)
        hc.bind_salt(DRAND_SALT,
                     salt_source={"beacon": "drand", "round": 3_366_570},
                     revealed_at=time.time())
        other = hashlib.sha256(b"what drand actually published").hexdigest()
        with pytest.raises(CommitmentOrderError, match="does not match"):
            hc.verify_salt_against_beacon(other, resolved_time=time.time())
        assert hc.fair_ordering is False
        c = hc.commitment
        assert c["order"] == "external_commitment_refuted"
        assert "REFUTED" in c["note"]
        assert c["beacon_verification"]["verified"] is False

    def test_seed_grind_against_published_beacon_not_certified_fair(self):
        # THE ROUND-5 EXPLOIT: grind the SECRET SEED against an
        # already-published beacon value (Bitcoin block 1's hash) until the
        # first rounds all bust below 2x, then bind the GENUINE block hash
        # with {"beacon": "bitcoin", "height": 1} — a verifier's value
        # lookup matches byte-for-byte.  Every certification path must die.
        salt = BITCOIN_BLOCK_1_HASH
        tries, seed = 0, None
        while seed is None:
            cand = f"grind-seed {tries}"
            chain = build_hash_chain(cand, 5)
            if all(crash_point_from_hash(h, salt) < 2.0
                   for h in chain[-2:-5:-1]):
                seed = cand
            tries += 1
        hc = HashChain(seed, length=5)
        source = {"beacon": "bitcoin", "height": 1}
        # (a) claim without revealed_at: refused outright
        with pytest.raises(CommitmentOrderError, match="revealed_at"):
            hc.bind_salt(salt, salt_source=source)
        # (b) honest revealed_at (2009): refused outright
        with pytest.raises(CommitmentOrderError, match="predates"):
            hc.bind_salt(salt, salt_source=source,
                         revealed_at=BITCOIN_BLOCK_1_TIME)
        # (c) LIE about the reveal time: binds only as an UNVERIFIED claim
        time.sleep(0.002)
        hc.bind_salt(salt, salt_source=source, revealed_at=time.time())
        assert all(p < 2.0 for p in hc.crash_points(3))  # rig works...
        assert hc.fair_ordering is False                 # ...never certified
        assert (hc.commitment["order"]
                == "external_commitment_claimed_unverified")
        # (d) the verifier resolves block 1 out-of-band: the value matches
        # byte-for-byte, but its TRUE publication time predates the
        # commitment -> claim refuted permanently
        with pytest.raises(CommitmentOrderError, match="BEFORE the chain"):
            hc.verify_salt_against_beacon(
                salt, resolved_time=BITCOIN_BLOCK_1_TIME
            )
        assert hc.fair_ordering is False
        assert hc.commitment["order"] == "external_commitment_refuted"
        assert "REFUTED" in hc.commitment["note"]
        # (e) a refuted claim cannot be revived, even by a later lying
        # verify call with a fabricated post-commitment resolved_time
        with pytest.raises(CommitmentOrderError, match="already refuted"):
            hc.verify_salt_against_beacon(salt, resolved_time=time.time())
        assert hc.fair_ordering is False

