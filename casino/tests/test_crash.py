    def test_ground_salt_attack_is_not_certified_fair(self):
        # The round-4 exploit: commit a chain, grind candidate salts until
        # the first rounds all bust below 2x, bind the winner.  The engine
        # must refuse to stamp the rigged chain fair_ordering=True — no
        # matter how the ground salt's salt_source is dressed.
        secret = "grind-target"
        length = 8
        hc = HashChain(secret, length=length)
        chain = build_hash_chain(secret, length)
        first_three = chain[-2:-5:-1]  # play order
        rigged, tries = None, 0
        while rigged is None:
            cand = hashlib.sha256(f"grind {tries}".encode()).hexdigest()
            tries += 1
            if all(crash_point_from_hash(h, cand) < 2.0 for h in first_three):
                rigged = cand
        # (a) dressed as a Bitcoin beacon claim: a ground SHA-256 salt has
        # ~0 leading zero nibbles — impossible for any block, refused
        hc_btc = HashChain(secret, length=length)
        time.sleep(0.002)
        with pytest.raises(CommitmentOrderError, match="leading zero"):
            hc_btc.bind_salt(rigged, salt_source=BEACON_SOURCE,
                             revealed_at=time.time())
        # (b) dressed as a drand claim (no leading-zero structure): binds
        # only as an UNVERIFIED claim; out-of-band resolution of the named
        # round returns a different value -> refuted
        hc_dr = HashChain(secret, length=length)
        time.sleep(0.002)
        hc_dr.bind_salt(rigged,
                        salt_source={"beacon": "drand", "round": 3_366_570},
                        revealed_at=time.time())
        assert all(p < 2.0 for p in hc_dr.crash_points(3))
        assert hc_dr.fair_ordering is False
        assert (hc_dr.commitment["order"]
                == "external_commitment_claimed_unverified")
        real_value = hashlib.sha256(b"the round's real randomness").hexdigest()
        with pytest.raises(CommitmentOrderError, match="does not match"):
            hc_dr.verify_salt_against_beacon(real_value,
                                             resolved_time=time.time())
        assert hc_dr.fair_ordering is False
        assert hc_dr.commitment["order"] == "external_commitment_refuted"
        # (c) confession-string source: recorded as operator-drawn
        hc.bind_salt(rigged, salt_source=f"ground in {tries} tries")
        assert all(p < 2.0 for p in hc.crash_points(3))  # rig worked...
        assert hc.fair_ordering is False                 # ...and is not certified
        assert hc.commitment["order"] == "operator_drawn_after_commitment"

